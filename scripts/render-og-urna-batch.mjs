#!/usr/bin/env node
import { createServer } from "node:http";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { spawnSync } from "node:child_process";
import { chromium } from "playwright";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const template = readFileSync(join(root, "scripts/og-urna-card.html"));
const outDir = join(root, "public/og/urna");
mkdirSync(outDir, { recursive: true });

const candidates = JSON.parse(
  readFileSync(join(root, "src/data/candidates.json"), "utf8"),
).candidates;
const racePollsFile = JSON.parse(
  readFileSync(join(root, "src/data/race-polls.json"), "utf8"),
);
const racePolls = Array.isArray(racePollsFile)
  ? racePollsFile
  : (racePollsFile.polls ?? []);

const PARTY_COLORS = {
  PT: "#d92524",
  PL: "#3e8ec2",
  PSD: "#c8a227",
  MDB: "#2a9583",
  PP: "#7cb342",
  PSDB: "#1565c0",
  UNIAO: "#546e7a",
  REPUBLICANOS: "#1b5e20",
  PDT: "#e65100",
  PSOL: "#fbc02d",
  NOVO: "#ff6f00",
  SOLIDARIEDADE: "#ff7043",
};

function partyColor(party) {
  const key = String(party ?? "")
    .normalize("NFD")
    .replace(/\p{M}/gu, "")
    .toUpperCase()
    .replace(/[^A-Z0-9]/g, "");
  return PARTY_COLORS[key] ?? "#2a9583";
}

function assetKey(c) {
  return `${c.uf.toLowerCase()}-${c.office}-${c.slug}`;
}

function officeLabel(c) {
  return c.office === "senator" ? "Senador" : "Governador";
}

function govName(slug, uf) {
  return (
    candidates.find((c) => c.office === "governor" && c.uf === uf && c.slug === slug)
      ?.name ?? slug
  );
}

function tightGovernorRaces(limit = 6) {
  const latest = new Map();
  for (const p of racePolls) {
    if (p.office !== "governor") continue;
    const prev = latest.get(p.uf);
    const key = `${p.date}|${p.fieldEnd}`;
    const prevKey = prev ? `${prev.date}|${prev.fieldEnd}` : "";
    if (!prev || key > prevKey) latest.set(p.uf, p);
  }
  const rows = [];
  for (const [uf, poll] of latest) {
    const ranked = Object.entries(poll.firstRound ?? {})
      .filter(([, v]) => typeof v === "number")
      .sort((a, b) => b[1] - a[1]);
    if (ranked.length < 2) continue;
    const [aSlug, aPct] = ranked[0];
    const [bSlug, bPct] = ranked[1];
    rows.push({
      uf,
      aName: govName(aSlug, uf),
      bName: govName(bSlug, uf),
      gap: aPct - bPct,
    });
  }
  return rows.sort((a, b) => a.gap - b.gap || a.uf.localeCompare(b.uf)).slice(0, limit);
}

const tight = tightGovernorRaces(6);
const slugSet = new Set();
for (const race of tight) {
  for (const name of [race.aName, race.bName]) {
    const hit = candidates.find(
      (c) =>
        c.office === "governor" &&
        c.uf === race.uf &&
        c.name === name &&
        String(c.number ?? "").trim(),
    );
    if (hit) slugSet.add(assetKey(hit));
  }
}

const targets = candidates.filter(
  (c) =>
    c.office !== "president" &&
    String(c.number ?? "").trim() &&
    slugSet.has(assetKey(c)),
);

if (targets.length === 0) {
  writeFileSync(
    join(root, "src/lib/og-urna-manifest.ts"),
    `/** Generated by scripts/render-og-urna-batch.mjs */\nexport const OG_URNA_KEYS = new Set<string>([]);\n`,
  );
  process.stdout.write("render-og-urna: no tight-race targets\n");
  process.exit(0);
}

const server = createServer((req, res) => {
  res.writeHead(200, { "content-type": "text/html; charset=utf-8" });
  res.end(template);
});
await new Promise((resolve) => server.listen(0, "127.0.0.1", resolve));
const { port } = server.address();

const browser = await chromium.launch({
  headless: true,
  args: ["--no-sandbox", "--disable-dev-shm-usage"],
});
const page = await browser.newPage({
  viewport: { width: 1200, height: 630 },
  deviceScaleFactor: 1,
});

let ok = 0;
for (const c of targets) {
  const color = partyColor(c.party);
  const qs = new URLSearchParams({
    num: c.number,
    name: c.name,
    detail: `${officeLabel(c)} · ${c.uf}`,
    party: c.party,
    color,
  });
  await page.goto(`http://127.0.0.1:${port}/?${qs}`, {
    waitUntil: "networkidle",
    timeout: 30000,
  });
  await page.evaluate(() => document.fonts.ready);
  await page.waitForTimeout(120);
  const pngPath = `/tmp/radar-urna-${assetKey(c)}.png`;
  const jpgPath = join(outDir, `${assetKey(c)}.jpg`);
  await page.screenshot({ path: pngPath, type: "png" });
  const ff = spawnSync("ffmpeg", ["-y", "-i", pngPath, "-q:v", "4", jpgPath], {
    encoding: "utf8",
  });
  if (ff.status === 0) {
    ok += 1;
    process.stdout.write(`wrote ${jpgPath}\n`);
  }
}

await browser.close();
server.close();

const keys = targets.map(assetKey);
writeFileSync(
  join(outDir, "manifest.json"),
  JSON.stringify({ generated: ok, keys }, null, 2),
);
writeFileSync(
  join(root, "src/lib/og-urna-manifest.ts"),
  `/** Generated by scripts/render-og-urna-batch.mjs */\nexport const OG_URNA_KEYS = new Set<string>([\n${keys.map((k) => `  "${k}",`).join("\n")}\n]);\n`,
);
process.stdout.write(`render-og-urna: ${ok}/${targets.length}\n`);
